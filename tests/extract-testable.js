const fs = require('fs');
const path = require('path');

const HTML_PATH = path.join(__dirname, '..', 'Marts_System_Merged.html');
const OUT_PATH = path.join(__dirname, '..', 'tests', '__extracted__.js');

const html = fs.readFileSync(HTML_PATH, 'utf8');
const scriptRegex = /<script[^>]*>([\s\S]*?)<\/script>/gi;
let allScripts = '';
let match;
while ((match = scriptRegex.exec(html)) !== null) {
  allScripts += match[1] + '\n';
}

// Extract specific function blocks
function extractBlock(code, name) {
  const patterns = [
    new RegExp(`(const ${name}\\s*=\\s*\\([^)]*\\)\\s*=>\\s*\\{[\\s\\S]*?\\}\\s*\\})`, 'm'),
    new RegExp(`(const ${name}\\s*=\\s*function[^}]*\\{[\\s\\S]*?\\}\\s*\\})`, 'm'),
    new RegExp(`(function\\s+${name}\\s*\\([^)]*\\)\\s*\\{[\\s\\S]*?\\}\\s*\\})`, 'm'),
  ];
  for (const p of patterns) {
    const m = code.match(p);
    if (m) return m[1];
  }
  return null;
}

function extractConstBlock(code, name) {
  const re = new RegExp(`(const ${name} = \\{[\\s\\S]*?\\n\\});`, 'm');
  const m = code.match(re);
  if (m) return m[1];
  return null;
}

// Build standalone module
let output = `// Auto-extracted testable functions from Marts_System_Merged.html
// DO NOT EDIT - regenerated by extract-testable.js

`;

// Simple pure functions
const simpleFuncs = ['uid', 'fmt', 'today', 'daysBetween', 'addDays', 'getInitials', 'getNextPayoutDate', 'genSaleCode'];
for (const fn of simpleFuncs) {
  const block = extractBlock(allScripts, fn);
  if (block) {
    output += block + '\n\n';
  }
}

// isSalesSide / isMarketingSide
for (const fn of ['isSalesSide', 'isMarketingSide', 'isOwner', 'isAdmin', 'canAccounting', 'canManageUser', 'hasPermission', 'getRoleLabel', 'getRoleType', 'getRoleConfig', 'getUserByUsername', 'getChildren', 'getTeamUserIds', 'getDirectReports', 'getAllUsers', 'getAllRoles', 'getResaleTeam', 'isLocked']) {
  const block = extractBlock(allScripts, fn);
  if (block) {
    output += block + '\n\n';
  }
}

// STORAGE object
const storageBlock = extractConstBlock(allScripts, 'STORAGE');
if (storageBlock) {
  output += storageBlock + '\n\n';
}

// safeStorage object
const safeStorageBlock = extractConstBlock(allScripts, 'safeStorage');
if (safeStorageBlock) {
  output += safeStorageBlock + '\n\n';
}

// ActivityLog object
const actLogBlock = extractConstBlock(allScripts, 'ActivityLog');
if (actLogBlock) {
  output += actLogBlock + '\n\n';
}

// FirebaseSync (stub if not found)
output += `
const FirebaseSync = {
  save: function() { return Promise.resolve(); },
  load: function() { return Promise.resolve(); }
};
`;

// toggleLockEntry
const toggleLockBlock = extractBlock(allScripts, 'toggleLockEntry');
if (toggleLockBlock) {
  output += toggleLockBlock + '\n\n';
}

// WorkPatternLearner
const wplBlock = extractConstBlock(allScripts, 'WorkPatternLearner');
if (wplBlock) {
  output += wplBlock + '\n\n';
}

// Export
output += `
module.exports = {
  uid, fmt, today, daysBetween, addDays, getInitials, getNextPayoutDate, genSaleCode,
  isSalesSide, isMarketingSide, isOwner, isAdmin, canAccounting, canManageUser, hasPermission,
  getRoleLabel, getRoleType, getRoleConfig, getUserByUsername, getChildren, getTeamUserIds,
  getDirectReports, getAllUsers, getAllRoles, getResaleTeam, isLocked, toggleLockEntry,
  STORAGE, safeStorage, ActivityLog, WorkPatternLearner, FirebaseSync
};
`;

fs.writeFileSync(OUT_PATH, output, 'utf8');
console.log(`Extracted testable functions to ${OUT_PATH}`);
console.log(`Output length: ${output.length} chars`);
